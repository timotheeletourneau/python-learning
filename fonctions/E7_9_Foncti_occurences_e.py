def compteCar(ca, ch):
    # 'ca' représente le caractère que l'on souhaite compter dans la chaîne 'ch'
    ma_chaîne = ch  # Assigne la chaîne d'entrée à la variable 'ma_chaîne'
    
    # Compte le nombre d'occurrences de 'ca' dans 'ma_chaîne'
    nombre_de_e = ma_chaîne.count(ca)
    
    # Retourne le nombre trouvé
    return nombre_de_e




     
        
        
        
