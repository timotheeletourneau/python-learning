def inverse(ch):
    # Prend une chaîne de caractères 'ch' comme argument
    ma_chaîne = ch  # Stocke la chaîne d'entrée dans la variable 'ma_chaîne'
    
    # Inverse la chaîne en utilisant le slicing (de la fin au début)
    resultat = ma_chaîne[::-1]
    
    # Retourne la chaîne inversée
    return resultat
