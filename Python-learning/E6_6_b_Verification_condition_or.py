# Initialisation des variables a et b
a, b = 2, 4

# Vérifie si a est égal à 4 ou si b n'est pas égal à 4
if (a == 4) or (b != 4):
    # Condition remplie si a est égal à 4 ou b est différent de 4
    print('gagné')
# Vérifie si a est égal à 4 ou si b est égal à 4
elif (a == 4) or (b == 4):
    # Condition remplie si a est égal à 4 ou b est égal à 4
    print('presque gagné')
